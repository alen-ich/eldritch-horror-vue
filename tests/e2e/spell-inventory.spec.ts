import { test, expect } from '@playwright/test'

test('Spell supply exposes a read-only front and survives reconnect', async ({ browser }) => {
  const hostContext = await browser.newContext()
  const guestContext = await browser.newContext()
  try {
    const host = await hostContext.newPage()
    const guest = await guestContext.newPage()
    await host.goto('/')
    await host.waitForLoadState('networkidle')
    await host.getByLabel('Display name').fill('Spell Host')
    await host.getByRole('button', { name: 'Create game' }).click()
    await expect(host.getByText('Investigator roster')).toBeVisible()
    await guest.goto(host.url())
    await guest.waitForLoadState('networkidle')
    await expect(guest.getByText('Investigator roster')).toBeVisible()
    await host.getByRole('button', { name: /Trish Scarborough/i }).click()
    await expect(guest.locator('.roster article').filter({ hasText: 'Trish Scarborough' })).toBeVisible()
    await guest.getByRole('button', { name: /Mark Harrigan/i }).click()
    await expect(host.locator('.roster article').filter({ hasText: 'Mark Harrigan' })).toBeVisible()
    await host.getByRole('button', { name: /Azathoth.*Doom 15/i }).click()
    await expect(host.getByRole('button', { name: 'Start game' })).toBeEnabled()
    await host.getByRole('button', { name: 'Start game' }).click()
    await host.getByRole('button', { name: /Spells/ }).click()
    const panel = host.getByRole('region', { name: 'Spell inventory' })
    await expect(panel.getByText('Feed the Mind supports casting. Other effects not implemented.')).toBeVisible()
    await expect(panel.getByText('No Spells held')).toBeVisible()
    const supply = panel.getByRole('img')
    await expect(supply).toBeVisible()
    const frontName = await supply.getAttribute('alt')
    expect(await panel.locator('button').count()).toBe(0)
    expect(await panel.getAttribute('data-physical-id')).toBeNull()
    await host.reload()
    await host.waitForLoadState('networkidle')
    await expect(host.getByRole('button', { name: /Spells/ })).toBeVisible()
    await host.getByRole('button', { name: /Spells/ }).click()
    await expect(host.getByRole('region', { name: 'Spell inventory' }).getByRole('img')).toHaveAttribute('alt', frontName!)
  } finally {
    await Promise.allSettled([hostContext.close(), guestContext.close()])
  }
})
