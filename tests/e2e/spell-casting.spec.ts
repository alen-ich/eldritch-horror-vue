import { test, expect } from '@playwright/test'
test('Norman pays Sanity without Clues and restores the owner choice after reload', async ({ browser }) => {
  const a=await browser.newContext(),b=await browser.newContext()
  try {
    const host=await a.newPage(),guest=await b.newPage()
    await host.goto('/');await host.waitForLoadState('networkidle');await host.getByLabel('Display name').fill('Norman caster');await host.getByRole('button',{name:'Create game'}).click()
    await expect(host.getByText('Investigator roster')).toBeVisible()
    await guest.goto(host.url());await expect(guest.getByText('Investigator roster')).toBeVisible()
    await host.getByRole('button',{name:/Norman Withers/i}).click()
    await expect(guest.locator('.roster article').filter({hasText:'Norman Withers'})).toBeVisible()
    await guest.getByRole('button',{name:/Lily Chen/i}).click()
    await expect(host.locator('.roster article').filter({hasText:'Lily Chen'})).toBeVisible()
    await host.getByRole('button',{name:/Azathoth.*Doom 15/i}).click()
    await expect(host.getByRole('button',{name:'Start game'})).toBeEnabled();await host.getByRole('button',{name:'Start game'}).click()
    await host.getByRole('button',{name:/Spells/}).click()
    const inventory=host.getByRole('region',{name:'Spell inventory'})
    await inventory.getByRole('button',{name:'Cast Feed the Mind'}).click()
    const payment=host.getByRole('button',{name:'Spend 1 Sanity (Norman): reroll die 1',exact:true})
    await expect(payment).toBeVisible();await expect(guest.getByRole('button',{name:/Spend 1 Sanity/})).toHaveCount(0)
    await expect(host.getByRole('button',{name:/Spend 1 Clue: reroll/})).toHaveCount(0)
    await host.reload();await expect(payment).toBeVisible()
    await payment.focus();await host.keyboard.press('Enter');await host.getByRole('button',{name:'Use selected reroll',exact:true}).click()
    await expect(payment).toHaveCount(0);await expect(host.locator('.dock-vitals .sanity')).toHaveText('✦ 6')
    await host.reload();await expect(host.locator('.dock-vitals .sanity')).toHaveText('✦ 6');await expect(payment).toHaveCount(0)
    const hostDialog=host.getByRole('dialog').filter({hasText:'Spell action'})
    await hostDialog.getByRole('button',{name:'lily_chen',exact:true}).click()
    const guestDialog=guest.getByRole('dialog').filter({hasText:'Spell action'})
    await guestDialog.getByRole('button',{name:'Improve will twice (Lily)',exact:true}).click()
    await guestDialog.getByRole('button',{name:'Decline',exact:true}).click()
    await expect(guestDialog).toHaveCount(0)
    await host.getByRole('button',{name:/Spells/}).click()
    await expect(inventory.getByRole('button',{name:'Cast Feed the Mind'})).toBeDisabled()
    await expect(host.locator('.dock-vitals .sanity')).toHaveText('✦ 6')
    for(const page of [host,guest])expect(await page.locator('body').innerHTML()).not.toMatch(/investigatorAbilityUsage|normanClueSubstitutions|sourcePhysicalId|feedTheMindByPhysicalId|private-card-assets/)
  } finally {await a.close();await b.close()}
})
test('seeded held Spell survives reload, casts and restores recipient choice', async ({ browser }) => {
  const a=await browser.newContext(),b=await browser.newContext()
  try {
    const host=await a.newPage(),guest=await b.newPage()
    await host.goto('/');await host.waitForLoadState('networkidle');await host.getByLabel('Display name').fill('Spell caster');await host.getByRole('button',{name:'Create game'}).click()
    await expect(host.getByText('Investigator roster')).toBeVisible()
    await guest.goto(host.url());await expect(guest.getByText('Investigator roster')).toBeVisible()
    await host.getByRole('button',{name:/Jim Culver/i}).click()
    await expect(guest.locator('.roster article').filter({hasText:'Jim Culver'})).toBeVisible()
    await guest.getByRole('button',{name:/Lily Chen/i}).click()
    await expect(host.locator('.roster article').filter({hasText:'Lily Chen'})).toBeVisible()
    await host.getByRole('button',{name:/Azathoth.*Doom 15/i}).click()
    await expect(host.getByRole('button',{name:'Start game'})).toBeEnabled();await host.getByRole('button',{name:'Start game'}).click()
    await host.getByRole('button',{name:/Spells/}).click()
    const inventory=host.getByRole('region',{name:'Spell inventory'})
    await expect(inventory.getByRole('heading',{name:'Feed the Mind',exact:true})).toBeVisible()
    await host.reload();await host.getByRole('button',{name:/Spells/}).click()
    await expect(inventory.getByRole('heading',{name:'Feed the Mind',exact:true})).toBeVisible()
    await inventory.getByRole('button',{name:'Cast Feed the Mind'}).click()
    await host.getByRole('button',{name:'Keep result',exact:true}).click()
    const hostDialog=host.getByRole('dialog').filter({hasText:'Spell action'})
    await hostDialog.getByRole('button',{name:'lily_chen',exact:true}).click()
    const guestDialog=guest.getByRole('dialog').filter({hasText:'Spell action'})
    await expect(guestDialog.getByRole('button',{name:'Improve lore twice (Lily)',exact:true})).toBeVisible()
    await expect(hostDialog).toHaveCount(0)
    await expect(host.getByText('Waiting for another investigator’s Spell choice.')).toBeVisible()
    await guest.reload()
    const improve=guestDialog.getByRole('button',{name:'Improve lore twice (Lily)',exact:true})
    await expect(improve).toBeVisible();await improve.focus();await guest.keyboard.press('Enter')
    await expect(guestDialog.getByRole('button',{name:'Decline',exact:true})).toBeVisible()
    await guestDialog.getByRole('button',{name:'Decline',exact:true}).click()
    await expect(guestDialog).toHaveCount(0)
    await expect(inventory.getByRole('button',{name:'Cast Feed the Mind'})).toBeDisabled()
    for(const page of [host,guest]) expect(await page.locator('body').innerHTML()).not.toMatch(/sourcePhysicalId|feedTheMindByPhysicalId|private-card-assets/)
  } finally {await a.close();await b.close()}
})
