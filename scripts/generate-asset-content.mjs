import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const sourcePath = path.join(root, "source-assets", "assets", "eldritch_horror_base_assets.json");
const outputPath = path.join(root, "packages", "content", "src", "assets.generated.ts");
const source = JSON.parse(await readFile(sourcePath, "utf8"));

if (!Array.isArray(source) || source.length !== 40) throw new Error("Expected exactly 40 base-game Asset records.");

const records = source.map((card, index) => {
  const expectedPrefix = `${String(index + 1).padStart(2, "0")}_`;
  if (card.card_type !== "Asset" || card.set !== "Eldritch Horror Base Game") throw new Error(`Unexpected card classification for ${card.id}.`);
  if (typeof card.image_filename !== "string" || !card.image_filename.startsWith(expectedPrefix)) throw new Error(`Unexpected source order for ${card.id}.`);
  if (card.image_filename !== `${expectedPrefix}${card.id}.jpg`) throw new Error(`Asset ID does not match its image filename: ${card.id}.`);
  return {
    id: `asset_${card.id}`,
    name: card.name,
    value: card.value,
    traits: card.traits.map((trait) => trait.toLowerCase()),
    abilityType: card.ability_type.replaceAll(" + ", " and ").replaceAll(" ", "_"),
    effectText: card.effect,
    sourceImageFilename: card.image_filename,
  };
});

const ids = new Set(records.map(({ id }) => id));
if (ids.size !== records.length) throw new Error("Asset source contains duplicate IDs.");

const output = `// Generated by scripts/generate-asset-content.mjs from the supplied base-game Asset JSON.\n` +
  `// Do not edit this file manually.\n\n` +
  `export const baseGameAssetDefinitions = ${JSON.stringify(records, null, 2)} as const;\n`;

await writeFile(outputPath, output);
console.log("Generated normalized metadata for 40 base-game Assets.");
